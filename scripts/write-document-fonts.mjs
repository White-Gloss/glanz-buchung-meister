import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { gzipSync } from "node:zlib";

// Regenerate only from the licensed, pinned local TTF instances. No network I/O.
const sourceDirectory = process.argv[2];
assert.ok(sourceDirectory, "Usage: node scripts/write-document-fonts.mjs <local-font-directory>");
const manifest = JSON.parse(await readFile(new URL("../public/fonts/font-source-manifest.json", import.meta.url), "utf8"));
const files = {
  body: "plus-jakarta-sans-400.ttf",
  bodyStrong: "plus-jakarta-sans-500.ttf",
  heading: "syne-700.ttf",
  numbers: "syne-800.ttf",
  fallback: "NotoSans-fallback.ttf",
};
const compressed = {};
for (const [role, filename] of Object.entries(files)) {
  const bytes = await readFile(resolve(sourceDirectory, filename));
  assert.equal(createHash("sha256").update(bytes).digest("hex"), manifest.files[filename].sha256, filename);
  compressed[role] = gzipSync(bytes, { level: 9 }).toString("base64");
}
await writeFile(
  new URL("../src/lib/document-font-data.generated.ts", import.meta.url),
  "// Generated by scripts/write-document-fonts.mjs; licensed sources and SHA256 in public/fonts.\n" +
    "// Embedded server data keeps newly generated PDFs independent of HTTP and working directories.\n" +
    `export const documentFontData = ${JSON.stringify(compressed, null, 2)} as const;\n`,
);
